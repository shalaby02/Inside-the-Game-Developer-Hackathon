"""Run the Personalizer for reader profiles and save data/personalized/<profile_key>.json.

Reads the frozen data (never changes it): data/key_moments.json,
data/narrations.json, data/analysis.json, data/match_summary.json and
data/player_summaries.json (run src/player_summary.py first). Reads
FOUNDRY_ENDPOINT, FOUNDRY_DEPLOYMENT and FOUNDRY_API_KEY from .env; the key
is only handed to the client, never printed or saved.

Each output file is a cache for its profile, like data/narrations.json: a
moment or recap that already passed with the same input, instructions and
rules is not redone, and a failed one is tried again. A hand edit (the saved
output differs from what the model last generated) is kept and re-checked,
never regenerated by a normal run.

  python src/run_personalizer.py                 the demo profiles (DEMO_PROFILES)
  python src/run_personalizer.py --profile fan/stadium/en/none/Cass\\ Dunmore
                                                 one profile: mode/voice/language/favourite_team[/focus_player]
  python src/run_personalizer.py --force         redo everything, hand edits included
  python src/run_personalizer.py --verify        check every saved file as it is, no model calls
                                                 (exit code 1 if anything fails)
"""

import hashlib
import json
import os
import sys
from pathlib import Path

from dotenv import load_dotenv
from openai import OpenAI, OpenAIError

import player_summary
import polish_check
import style_rules
import voices
from hello_foundry import openai_base_url
from personalizer import (CHECK_KEYS, MODEL_PARAMS, MOMENT_SCHEMA, RECAP_SCHEMA, build_moment_input,
                          build_recap_input, flagged, moment_instructions, personalize_moment,
                          personalize_recap, player_card, recap_context, recap_instructions,
                          run_moment_checks, run_recap_checks)
from profiles import Profile, ProfileError, involves_favourite, select, selection_problems

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT_DIR = DATA / "personalized"

DEMO_PROFILES = [
    {"mode": "analyst", "voice": "studio", "language": "en", "favourite_team": "none", "focus_player": "none"},
    {"mode": "fan", "voice": "studio", "language": "en", "favourite_team": "london_red", "focus_player": "none"},
    {"mode": "fan", "voice": "stadium", "language": "en", "favourite_team": "london_blue", "focus_player": "none"},
    {"mode": "fan", "voice": "stadium", "language": "en", "favourite_team": "none", "focus_player": "Cass Dunmore"},
]


def _read(name):
    return json.loads((DATA / name).read_text(encoding="utf-8"))


def load_data() -> dict:
    players = _read("player_summaries.json")
    if players != json.loads(json.dumps(player_summary.build())):
        sys.exit("data/player_summaries.json is out of date: run python src/player_summary.py")
    narrations = {n["id"]: n for n in _read("narrations.json")["narrations"]}
    return {"moments": _read("key_moments.json")["moments"], "narrations": narrations,
            "analysis": _read("analysis.json")["analysis"], "summary": _read("match_summary.json"),
            "players": players["players"]}


def input_hash(profile: Profile, inputs: dict, instructions: str, schema: dict) -> str:
    """Changes when the profile, the input, the instructions, the model settings or the check rules change."""
    blob = json.dumps([profile.to_dict(), inputs, instructions, MODEL_PARAMS, schema, style_rules.BLOCKED,
                       style_rules.DURATION, style_rules.MAX_NUMBERS, style_rules.TERMS, style_rules.BANNED_TERMS,
                       style_rules.CONNECTORS, style_rules.PERSONALIZER_BLOCKED, style_rules.FAN_BLOCKED, polish_check.CLUMSY,
                       voices.VOICES, voices.INTERJECTIONS], sort_keys=True)
    return hashlib.sha256(blob.encode()).hexdigest()[:16]


def manually_edited(entry: dict) -> bool:
    attempts = entry.get("attempts") or []
    return bool(entry.get("manually_edited")) or bool(attempts and entry.get("output") != attempts[-1]["output"])


def plan(profile: Profile, data: dict) -> dict:
    """Everything a profile needs, computed in code: the selection, each
    moment's input, the recap's input and context, and their cache keys."""
    moments = {m["id"]: m for m in data["moments"]}
    selected = select(profile, data["moments"], data["analysis"], data["players"])
    items = []
    for i in selected:
        narration = data["narrations"][i]
        if narration["status"] != "ok":
            sys.exit(f"narration {i} has status {narration['status']}; the Personalizer only uses checked narrations")
        inputs = build_moment_input(moments[i], narration["narration"], profile)
        items.append({"id": i, "inputs": inputs,
                      "involves_favourite": involves_favourite(profile, moments[i], data["players"]),
                      "hash": input_hash(profile, inputs, moment_instructions(profile), MOMENT_SCHEMA)})
    args = (profile, data["analysis"], data["summary"], data["moments"], data["players"])
    recap_inputs = build_recap_input(*args)
    return {"selected": selected, "moments": items, "recap_inputs": recap_inputs,
            "recap_context": recap_context(*args),
            "recap_hash": input_hash(profile, recap_inputs, recap_instructions(profile), RECAP_SCHEMA),
            "player": player_card(profile, data["players"])}


def out_path(profile: Profile) -> Path:
    return OUT_DIR / f"{profile.key()}.json"


def load_cache(profile: Profile):
    path = out_path(profile)
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def reuse(cached, h, recheck, label, force, log):
    """The cached entry if it can be kept (a hand edit, re-checked; or passed
    with the same hash), else None."""
    if not cached:
        return None
    if not force and manually_edited(cached):
        checks = recheck(cached.get("output"))
        log(f"{label}: manually edited, kept; checks {'pass' if checks['passed'] else 'FAIL'}")
        return {**cached, "manually_edited": True, "status": "ok" if checks["passed"] else "failed",
                "checks": {k: checks[k] for k in CHECK_KEYS}}
    if not force and cached.get("status") == "ok" and cached.get("input_hash") == h:
        log(f"{label}: cached")
        return cached
    if force and manually_edited(cached):
        log(f"{label}: --force is overwriting a manual edit")
    return None


def _failed(error):
    return {"status": "failed", "output": None, "checks": None, "retries": 0, "attempts": [], "error": error}


def run(profile: Profile, data: dict, cached, moment_one, recap_one, force=False, save_fn=lambda doc: None,
        log=print) -> dict:
    """Personalize what needs it and return the profile's document. moment_one(id)
    and recap_one() are the only things that call the model."""
    p = plan(profile, data)
    old = {e["id"]: e for e in (cached or {}).get("moments", [])}
    doc = {"profile": profile.to_dict(), "profile_key": profile.key(), "status": "failed",
           "selection": p["selected"], "player": p["player"], "moments": [], "recap": None}

    def attempt(fn):
        try:
            return fn()
        except OpenAIError as e:  # the message never includes the key
            return _failed(f"{type(e).__name__}: {e}")

    for item in p["moments"]:
        i = item["id"]
        entry = reuse(old.get(i), item["hash"], lambda out: run_moment_checks(out, item["inputs"], profile),
                      i, force, log)
        if entry is None:
            entry = {"id": i, **attempt(lambda: moment_one(i)), "input_hash": item["hash"]}
            log(f"{i}: {entry['status']}, {entry['retries']} retr{'y' if entry['retries'] == 1 else 'ies'}")
        # Selection metadata, computed in code; not part of the model's input or cache key.
        entry = {"id": i, "involves_favourite": item["involves_favourite"],
                 **{k: v for k, v in entry.items() if k not in ("id", "involves_favourite")}}
        doc["moments"].append(entry)
        save_fn(doc)

    recheck = lambda out: run_recap_checks(out, p["recap_inputs"], p["recap_context"], profile)  # noqa: E731
    recap = reuse((cached or {}).get("recap"), p["recap_hash"], recheck, "recap", force, log)
    if recap is None:
        recap = {**attempt(recap_one), "input_hash": p["recap_hash"]}
        log(f"recap: {recap['status']}, {recap['retries']} retr{'y' if recap['retries'] == 1 else 'ies'}")
    doc["recap"] = recap
    doc["status"] = "ok" if all(e["status"] == "ok" for e in doc["moments"] + [recap]) else "failed"
    save_fn(doc)
    return doc


def verify(path: Path, data: dict) -> tuple:
    """(passed, lines) for one saved file as it is now. No model calls."""
    doc = json.loads(path.read_text(encoding="utf-8"))
    try:
        profile = Profile.from_dict(doc.get("profile"), players=data["players"])
    except ProfileError as e:
        return False, [f"profile: {e}"]
    lines = []
    if path.stem != profile.key():
        lines.append(f"file name {path.name} does not match the profile key {profile.key()}")
    ids = [e.get("id") for e in doc.get("moments", [])]
    lines += [f"selection: {p}" for p in selection_problems(profile, ids, data["moments"], data["analysis"],
                                                            data["players"])]
    if doc.get("selection") != ids:
        lines.append("selection list does not match the saved moments")
    p = plan(profile, data)
    if doc.get("player") != p["player"]:
        lines.append("player facts differ from data/player_summaries.json for this profile")

    moments = {m["id"]: m for m in data["moments"]}
    for entry in doc.get("moments", []):
        i = entry.get("id")
        if i not in moments or i not in data["narrations"]:
            continue
        if entry.get("involves_favourite") != involves_favourite(profile, moments[i], data["players"]):
            lines.append(f"{i}: involves_favourite should be {involves_favourite(profile, moments[i], data['players'])}")
        inputs = build_moment_input(moments[i], data["narrations"][i]["narration"], profile)
        lines += [f"{i}: {line}" for line in flagged(run_moment_checks(entry.get("output"), inputs, profile))]
    recap = doc.get("recap") or {}
    lines += [f"recap: {line}" for line in flagged(
        run_recap_checks(recap.get("output"), p["recap_inputs"], p["recap_context"], profile))]
    notes = [f"note: {e.get('id', 'recap')} is manually edited"
             for e in doc.get("moments", []) + [recap] if manually_edited(e)]
    hashes = {e.get("id"): e.get("input_hash") for e in doc.get("moments", [])}
    if any(hashes.get(m["id"]) != m["hash"] for m in p["moments"]) or recap.get("input_hash") != p["recap_hash"]:
        notes.append("note: inputs, instructions or rules changed since it was generated")
    return not lines, notes + lines


def main() -> int:
    data = load_data()
    args = sys.argv[1:]

    if "--verify" in args:
        paths = sorted(OUT_DIR.glob("*.json"))
        if not paths:
            print("no files in data/personalized")
            return 1
        ok = True
        for path in paths:
            passed, lines = verify(path, data)
            ok &= passed
            print(f"{path.name}: {'PASS' if passed else 'FAIL'}")
            for line in lines:
                print(f"    {line}")
        return 0 if ok else 1

    try:
        if "--profile" in args:
            profiles = [Profile.parse(args[args.index("--profile") + 1], players=data["players"])]
        else:
            profiles = [Profile.from_dict(p, players=data["players"]) for p in DEMO_PROFILES]
    except (ProfileError, IndexError) as e:
        sys.exit(f"bad profile: {e}")

    load_dotenv(ROOT / ".env")
    missing = [n for n in ("FOUNDRY_ENDPOINT", "FOUNDRY_DEPLOYMENT", "FOUNDRY_API_KEY") if not os.getenv(n)]
    if missing:
        sys.exit(f"Missing in .env: {', '.join(missing)}")
    deployment = os.environ["FOUNDRY_DEPLOYMENT"]
    client = None

    def get_client():
        nonlocal client
        if client is None:  # only connect if something actually needs the model
            client = OpenAI(base_url=openai_base_url(os.environ["FOUNDRY_ENDPOINT"]),
                            api_key=os.environ["FOUNDRY_API_KEY"])
        return client

    OUT_DIR.mkdir(exist_ok=True)
    moments = {m["id"]: m for m in data["moments"]}
    ok = True
    for profile in profiles:
        print(f"\n{profile.key()}")
        def save(doc, profile=profile):
            out_path(profile).write_text(json.dumps({"model_deployment": deployment, **doc}, indent=2,
                                                    ensure_ascii=False) + "\n", encoding="utf-8")

        doc = run(profile, data, load_cache(profile),
                  lambda i, profile=profile: personalize_moment(get_client(), deployment, moments[i],
                                                                data["narrations"][i]["narration"], profile),
                  lambda profile=profile: personalize_recap(
                      get_client(), deployment, profile, data["analysis"], data["summary"], data["moments"],
                      data["players"]),
                  force="--force" in args, save_fn=save)
        failed = [e["id"] for e in doc["moments"] if e["status"] != "ok"] + (
            ["recap"] if doc["recap"]["status"] != "ok" else [])
        ok &= not failed
        print(f"{profile.key()}: {doc['status']}" + (f" (failed: {', '.join(failed)})" if failed else ""))
        print(f"Saved {out_path(profile).relative_to(ROOT)}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
