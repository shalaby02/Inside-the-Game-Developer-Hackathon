"""Run the Analyst and save the result to data/analysis.json.

Reads data/key_moments.json and data/match_summary.json (never changes
them; run src/match_summary.py first) and FOUNDRY_ENDPOINT,
FOUNDRY_DEPLOYMENT and FOUNDRY_API_KEY from .env. The key is only handed to
the client, never printed or saved.

data/analysis.json is a cache, like data/narrations.json: an analysis that
already passed with the same input, instructions and rules is not redone. A
failed one is tried again on the next run. A hand edit (the saved analysis
differs from what the model last generated) is kept and re-checked, never
regenerated by a normal run.

  python src/run_analyst.py            analyse if needed
  python src/run_analyst.py --force    redo it, hand edits included
  python src/run_analyst.py --verify   check data/analysis.json as it is, no model calls
                                       (exit code 1 if it fails)
"""

import hashlib
import json
import os
import sys
from pathlib import Path

from dotenv import load_dotenv
from openai import OpenAI, OpenAIError

import match_summary
import polish_check
import style_rules
from analyst import INSTRUCTIONS, MODEL_PARAMS, OUTPUT_SCHEMA, analyse, analyst_input, flagged, run_checks
from hello_foundry import openai_base_url

ROOT = Path(__file__).resolve().parent.parent
MOMENTS_PATH = ROOT / "data" / "key_moments.json"
SUMMARY_PATH = ROOT / "data" / "match_summary.json"
OUT_PATH = ROOT / "data" / "analysis.json"
CHECK_KEYS = ("format_problems", "grounding", "style", "polish", "terms")


def input_hash(inputs: dict) -> str:
    """Changes when the input, the instructions, the model settings or the check rules change."""
    blob = json.dumps([inputs, INSTRUCTIONS, MODEL_PARAMS, OUTPUT_SCHEMA, style_rules.BLOCKED,
                       style_rules.DURATION, style_rules.MAX_NUMBERS, style_rules.TERMS,
                       style_rules.BANNED_TERMS, style_rules.CONNECTORS, polish_check.CLUMSY], sort_keys=True)
    return hashlib.sha256(blob.encode()).hexdigest()[:16]


def manually_edited(entry: dict) -> bool:
    attempts = entry.get("attempts") or []
    return bool(entry.get("manually_edited")) or bool(attempts and entry.get("analysis") != attempts[-1]["analysis"])


def load_inputs() -> dict:
    summary = json.loads(SUMMARY_PATH.read_text(encoding="utf-8"))
    if summary != json.loads(json.dumps(match_summary.build())):
        sys.exit("data/match_summary.json is out of date: run python src/match_summary.py")
    return analyst_input(json.loads(MOMENTS_PATH.read_text(encoding="utf-8")), summary)


def load_cache():
    return json.loads(OUT_PATH.read_text(encoding="utf-8")) if OUT_PATH.exists() else None


def save(entry: dict) -> None:
    OUT_PATH.write_text(json.dumps(entry, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def recheck(entry: dict, inputs: dict) -> dict:
    """The saved analysis re-checked as it is now: a copy of entry with fresh checks and status."""
    checks = run_checks(entry.get("analysis"), inputs)
    return {**entry, "status": "ok" if checks["passed"] else "failed",
            "checks": {k: checks[k] for k in CHECK_KEYS}}


def run(inputs: dict, cached, analyse_one, force: bool = False, log=print) -> dict:
    """Analyse if needed and return the entry to save. analyse_one() is the
    only thing that calls the model; cached and hand-edited analyses never reach it."""
    h = input_hash(inputs)
    if cached and not force and manually_edited(cached):
        entry = {**recheck(cached, inputs), "manually_edited": True}
        log(f"manually edited, kept; checks {'pass' if entry['status'] == 'ok' else 'FAIL'}")
        if cached.get("input_hash") != h:
            log("    note: its inputs have changed since it was generated; --force would regenerate it")
        return entry
    if cached and not force and cached.get("status") == "ok" and cached.get("input_hash") == h:
        log("cached")
        return cached
    if cached and force and manually_edited(cached):
        log("--force is overwriting a manual edit")
    try:
        entry = analyse_one()
    except OpenAIError as e:  # the message never includes the key
        entry = {"status": "failed", "analysis": None, "checks": None, "retries": 0, "attempts": [],
                 "error": f"{type(e).__name__}: {e}"}
    entry["input_hash"] = h
    log(f"{entry['status']}, {entry['retries']} retr{'y' if entry['retries'] == 1 else 'ies'}")
    return entry


def verify(inputs: dict, cached) -> tuple:
    """(passed, lines) for data/analysis.json as it is now. No model calls."""
    if not cached or not cached.get("analysis"):
        return False, ["no analysis saved"]
    checks = run_checks(cached["analysis"], inputs)
    notes = ["manually edited"] if manually_edited(cached) else []
    if cached.get("input_hash") != input_hash(inputs):
        notes.append("inputs or rules changed since it was generated")
    return checks["passed"], [f"note: {n}" for n in notes] + flagged(checks)


def main() -> int:
    inputs = load_inputs()
    cached = load_cache()

    if "--verify" in sys.argv:
        passed, lines = verify(inputs, cached)
        print(f"analysis: {'PASS' if passed else 'FAIL'}")
        for line in lines:
            print(f"    {line}")
        return 0 if passed else 1

    load_dotenv(ROOT / ".env")
    missing = [n for n in ("FOUNDRY_ENDPOINT", "FOUNDRY_DEPLOYMENT", "FOUNDRY_API_KEY") if not os.getenv(n)]
    if missing:
        sys.exit(f"Missing in .env: {', '.join(missing)}")
    deployment = os.environ["FOUNDRY_DEPLOYMENT"]

    def analyse_one():
        client = OpenAI(base_url=openai_base_url(os.environ["FOUNDRY_ENDPOINT"]),
                        api_key=os.environ["FOUNDRY_API_KEY"])
        return analyse(client, deployment, inputs)

    entry = run(inputs, cached, analyse_one, force="--force" in sys.argv)
    save({"model_deployment": deployment, **{k: v for k, v in entry.items() if k != "model_deployment"}})
    if entry.get("checks"):
        for line in flagged(entry["checks"]):
            print(f"    {line}")
    if entry.get("error"):
        print(f"    error: {entry['error']}")
    print(f"Saved {OUT_PATH.relative_to(ROOT)}")
    return 0 if entry["status"] == "ok" else 1


if __name__ == "__main__":
    sys.exit(main())
